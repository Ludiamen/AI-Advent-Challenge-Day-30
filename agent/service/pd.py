"""Персональные данные в тексте: поиск и маска (telegram-spec FR-T07, telegram-plan D-T10).

Шаблоны появились в Дне 29 — отбор вопросов без ПД для арендованного GPU
(`agent/rag/optbench.py`, `без_пд` — теперь отсюда). В Дне 30 Telegram-бот отправляет
ответы по документам во внешнее облако, и перед отправкой найденное заменяется маской.

Фамилии подписантов в коде не хранятся: репозиторий публичный. Список (по основе на
строку) — локальный файл pd-names.txt в корне проекта (в .gitignore) или путь из
PD_NAMES. Без файла остаются общие признаки: отчество, инициалы, e-mail, телефон.

Чего шаблоны НЕ ловят — `НЕ_ЛОВИТ`: это говорится владельцу в /help бота и в документах.

  найти(текст) -> виды находок (сами совпадения не возвращаются)
  скрыть(текст) -> (текст с «[скрыто]», {вид: сколько скрыто})
"""

from __future__ import annotations

import os
import re

ФАЙЛ_ФАМИЛИЙ = "pd-names.txt"
МАСКА = "[скрыто]"
НЕ_ЛОВИТ = "адреса, ИНН, КПП, ОГРН, расчётные счета, паспортные данные, фамилии не из списка"


def фамилии() -> tuple[str, ...]:
    путь = os.environ.get("PD_NAMES") or os.path.join(
        os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))), ФАЙЛ_ФАМИЛИЙ)
    try:
        with open(путь, encoding="utf-8") as f:
            return tuple(с.strip() for с in f if с.strip() and not с.lstrip().startswith("#"))
    except OSError:
        return ()


def список_есть() -> bool:
    """Есть ли список фамилий: без него фамилии не узнаются, и бот об этом предупреждает."""
    return bool(фамилии())


# Инициалы в документах пишутся по-разному, и распознавание добавляет своё: «А.В.», «А. В.»,
# «А.В» (без второй точки), «А В.». Шаблон Дня 29 знал только первые два — «М.В Фамилия» из живого
# ответа /doc ушла в Telegram (показ, сцена 5).
_ИНИЦИАЛЫ = r"(?:[А-ЯЁ]\.\s?[А-ЯЁ]\.?|[А-ЯЁ]\.?\s[А-ЯЁ]\.)"

ШАБЛОНЫ = (
    ("отчество", re.compile(r"\b[А-ЯЁ][а-яё]+(?:ович|евич|ьич|овна|евна|ична|инична)\b")),
    ("инициалы и фамилия", re.compile(r"\b" + _ИНИЦИАЛЫ + r"\s?[А-ЯЁ][а-яё]{2,}")),
    ("фамилия и инициалы", re.compile(r"\b[А-ЯЁ][а-яё]{2,}\s[А-ЯЁ]\.\s?[А-ЯЁ]\.?(?![А-Яа-яЁё])")),
    ("e-mail", re.compile(r"[\w.+-]+@[\w-]+\.[\w.]+")),
    ("телефон", re.compile(r"(?:\+7|8)[\s(-]*\d{3}[\s)-]*\d{3}[\s-]*\d{2}[\s-]*\d{2}")),
)
_ШАБЛОН = dict(ШАБЛОНЫ)


# Латинские двойники кириллицы. Распознанные договоры смешивают письмо: «M.B» латиницей перед
# кириллической фамилией — шаблоны с [А-ЯЁ] такое не видели, фамилия ушла в Telegram (показ,
# сцена 5). Поиск идёт по тексту, переведённому в кириллицу; замена посимвольная, длина та же —
# найденное маскируется в исходном тексте по тем же позициям.
_ДВОЙНИКИ = str.maketrans("ABCEHKMOPTXYaceopxy", "АВСЕНКМОРТХУасеорху")


def _кириллица(текст: str) -> str:
    return (текст or "").translate(_ДВОЙНИКИ)


def найти(текст: str) -> list[str]:
    """Что похоже на персональные данные: названия шаблонов (сами совпадения не возвращаются)."""
    ф = фамилии()
    шаблоны = ((("фамилия из списка", re.compile("|".join(map(re.escape, ф)))),) if ф else ()) + ШАБЛОНЫ
    норм = _кириллица(текст)
    return [имя for имя, ш in шаблоны if ш.search(норм)]


# Маска шире поиска: вместе с отчеством уходят имя (и фамилия) перед ним, фамилия из
# списка — целым словом от основы. Составные шаблоны — раньше одиночных: иначе от
# «И.И. Иванов» осталось бы «И.И. [скрыто]», а «Подписал И.И.» сошло бы за фамилию.
# Инициалы, оставшиеся рядом с маской (фамилию скрыл другой шаблон): «А В.[скрыто]» → «[скрыто]».
_ОСТАТКИ = re.compile(r"\b" + _ИНИЦИАЛЫ + r"\s?\[скрыто\]|\[скрыто\]\s?[А-ЯЁ]\.\s?[А-ЯЁ]\.?(?![А-Яа-яЁё])")
_ОТЧЕСТВО_С_ИМЕНЕМ = re.compile(r"(?:\b[А-ЯЁ][а-яё]+\s+){0,2}[А-ЯЁ][а-яё]+(?:ович|евич|ьич|овна|евна|ична|инична)\b")


def скрыть(текст: str) -> tuple[str, dict[str, int]]:
    """Заменить найденные ПД на «[скрыто]»; вернуть текст и сколько скрыто каждого вида."""
    маски: list[tuple[str, re.Pattern[str]]] = [
        ("инициалы и фамилия", _ШАБЛОН["инициалы и фамилия"]),
        ("фамилия и инициалы", _ШАБЛОН["фамилия и инициалы"]),
        ("отчество", _ОТЧЕСТВО_С_ИМЕНЕМ),
    ]
    ф = фамилии()
    if ф:
        маски.append(("фамилия из списка",
                      re.compile(r"[А-Яа-яЁё]*(?:" + "|".join(map(re.escape, ф)) + r")[А-Яа-яЁё]*")))
    маски += [("e-mail", _ШАБЛОН["e-mail"]), ("телефон", _ШАБЛОН["телефон"]), ("инициалы и фамилия", _ОСТАТКИ)]
    виды: dict[str, int] = {}
    текст = текст or ""
    for имя, шаблон in маски:
        части, конец, n = [], 0, 0
        for м in шаблон.finditer(_кириллица(текст)):
            части += [текст[конец:м.start()], МАСКА]
            конец, n = м.end(), n + 1
        if n:
            текст = "".join(части) + текст[конец:]
            виды[имя] = виды.get(имя, 0) + n
    return текст, виды
